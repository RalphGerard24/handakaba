// ─────────────────────────────────────────────────────────────────────────────
// Deterministic hash — same barangay name always produces the same offset.
// This replaces Math.random() so coordinates are stable across renders/reloads.
// ─────────────────────────────────────────────────────────────────────────────
const hashString = (str) => {
  let hash = 0
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i)
    hash = (hash << 5) - hash + char
    hash |= 0
  }
  return hash
}

const deterministicOffset = (seed, range = 0.004) => {
  const h = hashString(seed)
  const normalized = ((h & 0xFFFFFF) / 0xFFFFFF) - 0.5
  return normalized * range
}

// ─────────────────────────────────────────────────────────────────────────────
// Main geocoding function
// Resolution priority:
//   1. BARANGAY_COORDINATES  — exact entry for this barangay (best)
//   2. DISTRICT_COORDINATES  — district centre + deterministic barangay offset
//   3. CITY_COORDINATES      — city centre + deterministic offset (fallback)
// ─────────────────────────────────────────────────────────────────────────────
export const geocodeAddress = (city, district, barangay) => {
  // 1. Exact barangay hit
  const exactBarangay = BARANGAY_COORDINATES[city]?.[district]?.[barangay]
  if (exactBarangay) {
    return {
      lat: Number(exactBarangay[0].toFixed(6)),
      lng: Number(exactBarangay[1].toFixed(6)),
      precision: 'barangay',
    }
  }

  // 2. District centre + deterministic barangay spread (±~220 m)
  const districtCoords = DISTRICT_COORDINATES[city]?.[district]
  if (districtCoords) {
    const seed = `${city}|${district}|${barangay}`
    return {
      lat: Number((districtCoords[0] + deterministicOffset(seed + 'lat')).toFixed(6)),
      lng: Number((districtCoords[1] + deterministicOffset(seed + 'lng')).toFixed(6)),
      precision: 'district',
    }
  }

  // 3. City centre fallback
  const baseCoords = CITY_COORDINATES[city]
  if (!baseCoords) {
    console.warn(`No coordinates found for city: ${city}`)
    return { lat: 14.5995, lng: 120.9842, precision: 'default' }
  }

  const seed = `${city}|${district}|${barangay}`
  return {
    lat: Number((baseCoords[0] + deterministicOffset(seed + 'lat', 0.01)).toFixed(6)),
    lng: Number((baseCoords[1] + deterministicOffset(seed + 'lng', 0.01)).toFixed(6)),
    precision: 'city',
  }
}

